package com.example.ytclient.core.storage

import android.content.Context
import androidx.datastore.preferences.core.edit
import androidx.datastore.preferences.core.stringPreferencesKey
import androidx.datastore.preferences.preferencesDataStore
import kotlinx.coroutines.flow.first

/**
 * Tiny key→string DataStore wrapper exposed to the JS runtime via the
 * `__nativeStorageGet` / `__nativeStorageSet` bindings in `QuickJsRuntime`.
 *
 * Schema is intentionally untyped — the JS side stores its own JSON blob under
 * a single key (`yt_session`) containing visitorData, poToken, expiry, etc.
 * Keeping it untyped here means future runtime changes don't force Kotlin
 * migrations.
 */
class SessionStore(private val context: Context) {

    suspend fun get(key: String): String? {
        val prefs = context.dataStore.data.first()
        return prefs[stringPreferencesKey(key)]
    }

    suspend fun put(key: String, value: String) {
        context.dataStore.edit { it[stringPreferencesKey(key)] = value }
    }

    suspend fun remove(key: String) {
        context.dataStore.edit { it.remove(stringPreferencesKey(key)) }
    }

    private companion object {
        // Top-level property extension generated by `preferencesDataStore`.
        // Declared as a Context extension so the same DataStore instance is
        // shared across every SessionStore created from the app context.
        private val Context.dataStore by preferencesDataStore(name = "yt_runtime")
    }
}
